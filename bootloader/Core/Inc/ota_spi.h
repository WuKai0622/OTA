#ifndef __OTA_SPI_H
#define __OTA_SPI_H

#include <stdint.h>

#include "main.h"        /* SPI2_CS_Pin / SPI2_CS_GPIO_Port（PB12，软件片选） */
#include "ota_chan.h"    /* OTA_RxSink_t —— 与 ota_net.h 同型，见 ota_chan.h */

/* ==================== OTA SPI 通道（F407 主机 ←→ ESP32-C3 从机） ====================
 * 角色：**F407 做主机**，时钟由我们发；ESP32-C3 做从机，它把 SPI 收到的字节
 *       灌进 TCP 连接、把 TCP 收到的字节摆在 MISO 上。
 *
 * 接线（与 CubeMX 生成结果一致）：
 *   PB13 → SCK      PC3 → MOSI      PC2 → MISO      PB12 → CS
 *   ★ 供电：**一个电源供两块板，各走一对独立的 VCC/GND —— "共源、不共轨"**，
 *     两边的 **3V3 不要连**。这条是 2026-09-19 上板实测的**最终**结论，
 *     中间改过两次，把三次都记下来是因为前两次的**症状都很有欺骗性**：
 *       ① 两块板各用各的供电来源、（原文写的）只靠一根细地线相连 —— **不够**。
 *          两个来源各有各的地参考，WiFi 的脉冲回流叠上两边均流全挤在那根线上，
 *          地弹跳被打进 SPI 的判决电平。表现是**间歇性**坏帧（stale/badhdr 涨、
 *          字节账对不上），而 **TCP 连接全程没断** ⇒ 是信号被打坏、不是芯片复位
 *          —— 这两者的排查方向完全不同，先分清这一条能省掉一天。
 *       ② 于是试过把两边的 3V3 也直连 —— 坏帧压住了，但 **F407 的 3V3 轨变成由
 *          C3 的稳压器一起供着，LCD 狂闪**。屏能被电源波动刷到肉眼可见，说明轨
 *          在动的量级是**几百 mV**，而同一个量级足以打坏 3.3V 的 SPI 边沿：
 *          **屏闪和丢帧是同一个根因的两个表现，屏是那个看得见的金丝雀。**
 *       ③ 最终：一个电源供两块板、各走独立的一对线，3V3 不连 —— 升级成功且不再闪。
 *     详见 F103 工程 docs/OTA_WiFi_SPI通道方案.md 第二节（该文档未随本仓库发布）。
 *
 * 硬件参数：Mode 0（CPOL=0 低电平空闲 / CPHA=0 第一个边沿采样）、8bit、MSB first、
 *           全双工、软件 NSS、预分频 /32 → APB1 42MHz ÷ 32 = 1.3125MHz。
 *           ★ 起步必须慢：杜邦线没有地平面，快了必然振铃；先求通，再求快。
 *             （方案里"跑通后升到 5.25MHz"这一步留到本通道单独回归之后再做，
 *               一次只动一个变量。）
 *
 * 本文件分两层：
 *   物理层 —— 片选时序 + 一次定长事务的收发（OTA_Spi_Transfer）
 *   通道层 —— 事务循环、发送缓冲、状态统计（OTA_Spi_Poll / OTA_Spi_Send ...）
 * 协议层（帧解析、会话绑定）在 protocol.c，本文件不知道"帧"是什么。
 */

/* ---- 事务格式（与 C3 的 spi_bridge.h 是同一份契约，改一处必须改两处）----
 *
 *   MOSI (F407 → C3): [TX_LEN(2)][SQ(2)][RSV(4)]             + 256B 载荷
 *   MISO (C3 → F407): [RX_LEN(2)][STATUS(2)][HB(2)][RSV(2)]  + 256B 载荷
 *
 * ★ 两个长度名都是**站在 F407 的角度**命名的：
 *     TX_LEN = "F407 这一笔发了多少有效字节"
 *     RX_LEN = "F407 这一笔收到多少有效字节"（也就是 C3 发了多少）
 *   C3 侧正好反过来用，别被名字绕进去。
 *
 * ★ SQ = 每笔自增的**帧序号**（占用原 RSV 的前 2 字节）。
 *   它不是锦上添花，是实测踩出来的必需品：C3 侧判"这一笔有没有真的捕获到东西"
 *   不能只看驱动给的 trans_len —— 完全没有时钟进来时它会**保留上一笔的值**，
 *   于是同一块载荷被又投递了一遍（PC 收到双份，两端计数器都不报错）。
 *   C3 靠比对 SQ 拦下这种帧。**每开一笔事务都要自增，包括重发那一笔**：
 *   序号不变更就等于告诉 C3"这帧是旧的"。
 *
 * 全部**小端**。两端都是小端机，把字节序定死比省一次转换更重要 ——
 * 否则将来换个大端平台就会变成极难查的隐式 bug。
 *
 * ★ 为什么定长、不协商：变长要求两端各自算出**同一个数**，算错就时序错乱，
 *   是极难查的隐式耦合；两阶段协商又有循环依赖（master 发起事务前就得知道
 *   长度，但长度要在事务里才拿到）。定长直接把这个坑删掉。
 */
#define OTA_SPI_HDR_LEN       8u
#define OTA_SPI_PAYLOAD_LEN   256u

/* 一次事务的字节数：8 字节头 + 256 字节载荷 = 264。
 *
 * ★ 264 必须是 4 的倍数。ESP32-C3 侧启用 DMA 时，主机写入长度不是 4 的倍数
 *   会被**直接丢弃**（ESP-IDF 的通用约束，不是某款芯片专属）。264 = 4 × 66 ✓
 *   不知道这条，症状会是"偶尔丢几个字节 / 偶尔校验错 / 重发能过"，极难定位。 */
#define OTA_SPI_XFER_LEN      (OTA_SPI_HDR_LEN + OTA_SPI_PAYLOAD_LEN)

/* HAL 超时（ms）。1.3125MHz 下 264B ≈ 1.61ms，100ms 留足三个数量级余量，
 * 既能容忍从机偶尔没准备好，又不会在从机掉线时把 boot 卡死。 */
#define OTA_SPI_TIMEOUT_MS    100u

/* ---- 轮询节奏（ms）----
 * 一笔事务在 1.3125MHz 下要 **1.61ms 的忙等**（HAL 是阻塞式收发，168MHz 全用来
 * 轮询标志位）。所以"多久开一笔"直接等于"抢走多少 CPU"：
 *     2ms → 80%   5ms → 32%   8ms → 20%
 * 一律用 2ms 是不行的：走 ETH 的那次升级会被这套空转拖垮（lwIP 只剩 20% CPU）。
 * 于是分两档，切换判据是"这条链路最近有没有在动"：
 *     活动档 2ms  —— 拉满 SPI 这一路的吞吐（OTA 走 WiFi 时用）
 *     空闲档 8ms  —— 给 ETH 让路（OTA 走网口时用，此时 SPI 上本来就没字节）
 * 为什么这样切是安全的：走 WiFi 时 ETH 侧没有流量（那条闲置 TCP 连接不产生
 * 字节），20% 的 CPU 足够 lwIP 维持它；反过来走 ETH 时 SPI 上没有字节，
 * 空转 20% 也不影响什么。
 *
 * ★ 20ms 那个数从哪来：上位机 INTER_FRAME_GAP = 20ms（帧间最小停顿）。
 *   一个 DATA 帧 1036B 要 5 笔事务才搬完，要在 20ms 内搬完，间隔必须 ≤ 4ms。
 *   2ms 档留了一倍余量，所以 SPI 不会成为 OTA 的瓶颈（瓶颈在 PC 的帧间隔）。 */
#define OTA_SPI_ACTIVE_MS     2u
#define OTA_SPI_IDLE_MS       8u

/* 最后一笔有收发之后，保持"活动档"多久（ms）。
 * 不能一没字节就降档：帧与帧之间有 20ms 空档，一降档下一帧的头两笔就要
 * 按 8ms 走，白白把吞吐砍掉一截。200ms 覆盖了整个帧间空档还有富余。 */
#define OTA_SPI_ACTIVE_HOLD_MS  200u

/* 发送缓冲容量（字节）。**必须是 2 的幂**，用掩码代替取模。
 * 只需要装得下"上游还没被事务搬走的应答"：上位机是 stop-and-wait，
 * 同一时刻最多 1 个 ACK 帧（13B）在路上，512B 有 40 倍余量。 */
#define OTA_SPI_TX_BUF        512u

/* ---- 物理层 ---- */

/* 初始化物理层与通道层。必须在 MX_SPI2_Init() 之后调用。
 * sink 注入接收汇点：SPI 收到的字节交给它（boot 侧即 Bootloader_RingWrite）。 */
void    OTA_Spi_Init(OTA_RxSink_t sink);

/* 拆除物理层。跳转 app 之前必须调用，理由同 OTA_Net_DeInit()：
 * 不能让 SPI2 残留在已使能状态 —— app 会重新初始化它，两套配置打架。 */
void    OTA_Spi_DeInit(void);

/* 一次定长事务：片选拉低 → 全双工收发 len 字节 → 片选拉高。
 * 返回 0 = 成功，1 = HAL 超时/出错。
 * ★ 通道层之外不该有人直接调它（它是物理层），留着是为了让"物理层对不对"
 *   这件事可以被单独验证。 */
uint8_t OTA_Spi_Transfer(const uint8_t *tx, uint8_t *rx, uint16_t len);

/* ---- 通道层 ---- */

/* 跑**至多一笔**事务：把发送缓冲里的字节搬上 MOSI、把 MISO 收到的字节喂给 sink。
 * ★ 非阻塞，靠内部比时刻节流（见 OTA_SPI_ACTIVE_MS）。主循环每轮都调即可，
 *   没到点就立刻返回 —— 所以调用点不需要自己算间隔。
 *
 * ★★ 为什么必须**周期性**调它，而且必须在两个主循环里都调：
 *   SPI 的时钟是主机发的。不主动开事务，C3 那边收到的字节就永远上不来 ——
 *   它不是中断推给我们的。漏调的表现是"走 WiFi 的升级完全没反应"，
 *   而屏上 SPI 状态还显示得好好的（因为状态本身也是靠事务传回来的，
 *   一旦不调，屏上会停在最后一次的结论上）。 */
void    OTA_Spi_Poll(void);

/* 发送出口：注册给协议层（Proto_SetTx 的出口按通道号转进来）。
 * ★ 只是**入队**，不阻塞、不等待发完。返回 0 = 已入队，1 = 缓冲满。
 * 缓冲满时协议层不重发 —— 上位机的 stop-and-wait 超时重发兜底，两端职责不重叠。 */
uint8_t OTA_Spi_Send(const uint8_t *buf, uint16_t len);

/* ---- 排空发送队列时的放弃判据 ----
 * ★★ 这两个数不是调优，是**修一个真实缺陷**：本函数原来只有 timeout_ms 一个
 *   判据，而超时是在**每笔事务之前**查的，可一笔失败的 HAL 传输却要吃满
 *   OTA_SPI_TIMEOUT_MS = 100ms —— 100 > 50，于是**单独一次抖动就把整个预算
 *   耗光**、当场放弃，重试的那一笔根本没机会开出来。
 *
 *   症状正是"升级其实成功了，上位机却没收到最后应答"：OTA_END 的 ACK 还躺在
 *   队列里，紧接着 Upd_JumpToApp() 里的 OTA_Spi_DeInit() 把队列**连同 ACK 一起
 *   销毁**，此后 F407 已经在 app 里运行 —— 上位机那 END_RETRY = 3 次重发
 *   一笔都不可能被应答（重发的 END 只会堆在 C3 的接收环里，没人再取）。
 *   换句话说：**这根 ACK 是一发定生死的**，这里必须给它留足重试。
 *
 *   OTA_SPI_FLUSH_MS       —— 墙钟上限。正常路径一笔事务（1.61ms）就排空，
 *                             这个值只在链路病态时才会走满；两条通道上队列
 *                             本来就是空的，零开销。
 *   OTA_SPI_FLUSH_FAIL_MAX —— **连续**失败到几笔就认定链路是坏的、不再空耗。
 *                             成功一笔即清零，所以"时好时坏"仍然会一直重试 ——
 *                             而那正是最需要重试的情形。
 *   最坏阻塞 ≈ min(OTA_SPI_FLUSH_MS, FAIL_MAX × 100ms) + 一笔事务。 */
#define OTA_SPI_FLUSH_MS        2000u
#define OTA_SPI_FLUSH_FAIL_MAX  5u

/* 把**已入队但还没上总线**的字节跑事务推出去，最多等 timeout_ms。
 * 队列空时立刻返回（零开销），所以可以无条件调用。
 *
 * ★★ 两个调用点，都在 `update.c` 里，**两个都要留着，别删**：
 *     ① `Upd_OnDownloadComplete()` 的**第一行** —— 必需的那一处。OTA_END 的
 *        应答刚入队，紧接着就是秒级的擦扇区 + 拷 128KB，主循环全程回不来；
 *        不在这里推出去，上位机（END_TIMEOUT = 3.0s）必然超时重发并最终报
 *        "升级失败"，而固件其实已经写好了。
 *     ② `Upd_JumpToApp()` 里、`OTA_Spi_DeInit()` **之前** —— 队列被销毁前的
 *        最后一道。正常路径上①已经排空了，这里零开销；留着是因为"跳转"是本
 *        队列唯一的销毁点，将来任何在跳转前入队的应答都得靠它。
 *   区别只在于：删掉①会**立刻出故障**，删掉②暂时看不出问题。
 *     这是三条通道里只有 SPI 才有的问题：
 *       串口  —— HAL_UART_Transmit 是阻塞发送，返回即已上线；
 *       ETH   —— tcp_write + tcp_output 之后由 ETH DMA 搬走，而从入队到
 *                HAL_ETH_Stop 之间隔着整个 A→运行区的擦写（几百毫秒），
 *                早就发出去了。
 *
 * ★ 最坏阻塞时长 ≈ min(timeout_ms, OTA_SPI_FLUSH_FAIL_MAX × 100ms) **再加一笔
 *   事务** —— 一笔失败的 HAL 传输要 100ms，而超时是在每笔之前查的。
 *   两个调用点都传 OTA_SPI_FLUSH_MS（2000ms），理由见上面那段的算式：
 *   原来传 50ms 时，一笔事务失败就足以让整个预算作废。 */
void    OTA_Spi_FlushTx(uint32_t timeout_ms);

/* 在 (x, y) 画 SPI 通道的两行诊断，每 100ms 最多重画一次：
 *     SPI <结论 17 字符>
 *     RX <7 位>   e<4 位>
 * ★ 唯一目的：把"PC 发起了升级但没反应"这个笼统现象拆成能一眼看出是哪一段断了。
 *   结论四种：C3 NOT RESPONDING / WIFI DOWN / WAIT PC / LINK OK。
 *   四条串**必须等宽**（都补空格到 17 字符）—— LCD_DisplayString_color 只写
 *   strlen 个字符，由长变短时后面的格子不会被擦掉，屏上会读成
 *   "LINK OKRESPONDING" 这种东西。 */
void    OTA_Spi_ShowDiag(uint16_t x, uint16_t y);

/* ---- MISO 头里 STATUS 字段的位定义 ----
 * ★ 必须与 C3 侧 spi_bridge.h 的 SPI_BRIDGE_ST_WIFI / SPI_BRIDGE_ST_TCP 一致。
 *   这是跨编译单元的契约，写错了不会编译报错 —— 只会让屏上的结论跟实际反着显示，
 *   然后把人带沟里。所以在这里起个名字。 */
#define OTA_SPI_ST_WIFI       0x0001u
#define OTA_SPI_ST_TCP        0x0002u

#endif /* __OTA_SPI_H */
